def input_changes(before, after, path=""):
    """A readable exact change list, not a vague 'fixture adjusted' label."""
    if isinstance(before, dict) and isinstance(after, dict):
        changes = []
        for key in sorted(set(before) | set(after)):
            if key not in before or key not in after:
                changes.append({"path": path + "/" + key, "before_present": key in before,
                                "after_present": key in after, "before": before.get(key), "after": after.get(key)})
            else:
                changes.extend(input_changes(before[key], after[key], path + "/" + key))
        return changes
    if before != after:
        return [{"path": path, "before": before, "after": after}]
    return []


def frozen_cases(cases):
    ids = [case["case_id"] for case in cases]
    assert len(ids) == len(set(ids)) == len(CASE_SHA256), "case count/duplicate drift"
    assert set(ids) == set(CASE_SHA256), "case identity drift"
    for case in cases:
        assert digest(case) == CASE_SHA256[case["case_id"]], f"case content drift: {case['case_id']}"
    return {case["case_id"]: case for case in cases}



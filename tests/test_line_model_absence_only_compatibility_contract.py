def write_evidence(directory, name, row):
    with (directory / (name + ".json")).open("x", encoding="utf-8") as stream:
        json.dump(row, stream, ensure_ascii=False, indent=2, allow_nan=False)
        stream.write("\n")
        stream.flush()

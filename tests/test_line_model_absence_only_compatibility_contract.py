def evaluate_input(packet, output):
    """Actual raw and diagnostic repair; service-final selection stays separate."""
    before = digest({"packet": packet, "output": output})
    row = {}
    try:
        raw = audit.validate_model_analysis_v2(output, packet)
        row["raw"] = asdict(raw)
        repaired, codes = audit.deterministic_limitation_placeholder_repair(output, packet)
        row["repair_codes"] = list(codes)
        row["after_repair_output"] = deepcopy(repaired)
        after = audit.validate_model_analysis_v2(repaired if repaired is not None else output, packet)
        row["after_repair"] = asdict(after)
        # Match execute_line_model_shadow: rejected repair remains diagnostic;
        # only a PASSED repair replaces the raw verdict/reasons in service output.
        repair_attempted = not raw.passed and repaired is not None and bool(codes)
        use_repair = repair_attempted and after.passed
        row["service_final"] = asdict(after if use_repair else raw)
        row["service_repair_attempted"] = repair_attempted
        row["service_used_repair"] = use_repair
    except Exception as exc:
        row["exception"] = {"type": type(exc).__name__, "message": str(exc)}
    row["input_unchanged"] = before == digest({"packet": packet, "output": output})
    return row


def verdict_errors(result, expected_reasons, expected_rendered):
    errors = []
    expected_pass = expected_reasons == PASS
    if result["passed"] is not expected_pass:
        errors.append(f"passed={result['passed']!r}, expected={expected_pass}")
    if list(result["reason_codes"]) != expected_reasons:
        errors.append(f"reasons={result['reason_codes']!r}, expected={expected_reasons!r}")
    if list(result["rendered_blocks"]) != expected_rendered:
        errors.append(f"rendered={result['rendered_blocks']!r}, expected={expected_rendered!r}")
    return errors



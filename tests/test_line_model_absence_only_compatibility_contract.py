def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                   separators=(",", ":"), allow_nan=False).encode()).hexdigest()


def load_corpus(label):
    path, count, sha = CORPORA[label]
    data = (ROOT / path).read_bytes()
    assert hashlib.sha256(data).hexdigest() == sha, f"corpus drift: {path}"
    rows = [json.loads(line) for line in data.decode("utf-8-sig").splitlines()]
    assert len(rows) == count
    assert [row["attempt_index"] for row in rows] == list(range(1, count + 1))
    return rows


def legacy_fixture(name):
    """Read literal packet/output assignments, not a copied second fixture source."""
    tree = ast.parse((ROOT / LEGACY_TEST).read_text(encoding="utf-8"))
    function, = [node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == name]
    values = {}
    for node in function.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and target.id in {"packet", "output"}:
                assert target.id not in values, "ambiguous fixture assignment"
                values[target.id] = ast.literal_eval(node.value)
    assert set(values) == {"packet", "output"}
    return values, {"file": LEGACY_TEST, "function": name, "line": function.lineno,
                    "file_sha256": hashlib.sha256((ROOT / LEGACY_TEST).read_bytes()).hexdigest(),
                    "literal_input_sha256": digest(values)}


def literal_renderings(packet, output):
    """Expected positive text only; does not decide eligibility or call production."""
    facts = {fact["fact_id"]: fact for fact in packet["facts"]}
    result = []
    for block in output["explanation_blocks"]:
        text = block["text_template"]
        for fact_id, fact in facts.items():
            unit = {"TWD": " 元", "shares": " 股", "ratio": " 倍", "": ""}.get(fact.get("unit", ""), "")
            value = str(fact["value"])
            # Canonical renderer drops a nonsemantic .0 for integral floats.
            # Keep fractional values and source strings exact; never round.
            if isinstance(fact["value"], float) and fact["value"].is_integer():
                value = str(int(fact["value"]))
            if fact.get("quality") == "estimated":
                value = "推估 " + value
            text = text.replace("{{" + fact_id + "}}", value + unit)
        result.append(text)
    return result


